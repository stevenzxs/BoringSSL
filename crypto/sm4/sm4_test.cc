#include <openssl/sm4.h>
#include <string.h>
#include <gtest/gtest.h>

TEST(SM4Test, KnownAnswer) {
  const uint8_t key[16] = {0x01,0x23,0x45,0x67,0x89,0xab,0xcd,0xef,0xfe,0xdc,0xba,0x98,0x76,0x54,0x32,0x10};
  const uint8_t plain[16] = {0x01,0x23,0x45,0x67,0x89,0xab,0xcd,0xef,0xfe,0xdc,0xba,0x98,0x76,0x54,0x32,0x10};
  const uint8_t expected[16] = {0x68,0x1e,0xdf,0x34,0xd2,0x06,0x96,0x5e,0x86,0xb3,0xe9,0x4f,0x53,0x6e,0x42,0x46};
  SM4_KEY ks; uint8_t encrypted[16], decrypted[16];
  ASSERT_EQ(SM4_set_key(key, &ks), 0);
  SM4_encrypt(plain, encrypted, &ks);
  EXPECT_EQ(memcmp(encrypted, expected, 16), 0);
  SM4_decrypt(encrypted, decrypted, &ks);
  EXPECT_EQ(memcmp(decrypted, plain, 16), 0);
}
